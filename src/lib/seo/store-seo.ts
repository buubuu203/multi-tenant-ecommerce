// Store-level (home page / root layout) SEO: the Organization JSON-LD a
// search engine reads and the fallback description the root layout's
// generateMetadata uses when a tenant hasn't written store-level copy.
//
// Sibling to product-seo.ts, same reasons: pure, DOM-free, tenant-agnostic
// (every value comes from the caller's already-resolved branding, never a
// hardcoded host or store name), and unit-testable without a request
// context.

export type StoreSeoInput = {
  storeName: string;
  /** Branding.tagline, or null if the tenant hasn't set one. Short — shown in the footer and combined with storeName for the social-share title. */
  tagline: string | null;
  /**
   * Branding.ogDescription, or null. A longer, separate line for the meta/
   * Open Graph description and Organization JSON-LD — distinct from
   * `tagline` because a short brand line and a full search/share
   * description are different jobs (one tenant asked for exactly this
   * split: a punchy tagline plus a longer, keyword-bearing description).
   */
  ogDescription: string | null;
  /** Absolute origin of the CURRENT request. */
  origin: string;
  logoUrl: string | null;
  /** Social profile URLs already resolved for this tenant; falsy ones filtered by the caller. */
  socialUrls: (string | null)[];
};

/**
 * The description used for the store's root metadata. Prefers the
 * merchant's own ogDescription, then tagline (set in tenant-admin
 * branding); falls back to a generic line naming the store, which is
 * still more useful than Next's default "Generated by create next app".
 */
export function buildStoreDescription(
  input: Pick<StoreSeoInput, "storeName" | "tagline" | "ogDescription">,
): string {
  const ogDescription = input.ogDescription?.trim();
  if (ogDescription) return ogDescription;
  const tagline = input.tagline?.trim();
  return tagline || `${input.storeName} — cửa hàng trực tuyến`;
}

/**
 * The title a social share card / search snippet shows: the store name,
 * plus its short tagline when one is set. Deliberately distinct from the
 * plain `<title>` tag (which stays just the store name, for a clean
 * browser tab) — a share card has more room and benefits from the extra
 * context.
 */
export function buildStoreOgTitle(input: Pick<StoreSeoInput, "storeName" | "tagline">): string {
  const tagline = input.tagline?.trim();
  return tagline ? `${input.storeName} — ${tagline}` : input.storeName;
}

export type OrganizationJsonLd = {
  "@context": "https://schema.org";
  "@type": "Organization";
  name: string;
  url: string;
  description: string;
  logo?: string;
  sameAs?: string[];
};

/**
 * schema.org Organization markup for the storefront home page. `logo` is
 * omitted (not invented) when the tenant has none — an absent logo is
 * accurate; a placeholder one would misrepresent the brand. `sameAs` lists
 * only the social profiles the tenant actually filled in.
 */
export function buildStoreJsonLd(input: StoreSeoInput): OrganizationJsonLd {
  const sameAs = input.socialUrls.filter((url): url is string => Boolean(url?.trim()));
  return {
    "@context": "https://schema.org",
    "@type": "Organization",
    name: input.storeName,
    url: input.origin,
    description: buildStoreDescription(input),
    ...(input.logoUrl ? { logo: input.logoUrl } : {}),
    ...(sameAs.length > 0 ? { sameAs } : {}),
  };
}
