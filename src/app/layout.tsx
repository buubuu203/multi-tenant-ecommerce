import type { Metadata, Viewport } from 'next';
import { Be_Vietnam_Pro, Geist_Mono } from 'next/font/google';
import { ClerkProvider } from '@clerk/nextjs';
import { getCurrentTenant } from './_storefront/get-current-tenant';
import { resolveBranding } from './_storefront/resolve-branding';
import { getLocale, getDictionary } from '@/lib/i18n';
import { LocaleProvider } from '@/lib/i18n/locale-context';
import { DictionaryProvider } from '@/lib/i18n/use-dictionary';
import { getRequestOrigin } from '@/lib/seo/request-origin';
import { buildStoreDescription, buildStoreOgTitle } from '@/lib/seo/store-seo';
import './globals.css';

// Be Vietnam Pro is the storefront and admin typeface: a Vietnamese-first
// family, which matters here because every price is formatted in ₫ and
// product, address and customer data is routinely Vietnamese. The
// 'vietnamese' subset is what carries the stacked diacritics (ế, ữ, ộ) and
// the ₫ sign (U+20AB); loading 'latin' alone renders those from a fallback
// face and they visibly mismatch the rest of the text.
//
// Not a variable font on Google Fonts, so weights are explicit. These are
// exactly the three the codebase uses — 400 body, 500 for the 130
// font-medium call sites, 600 for the 27 font-semibold ones — rather than
// the full 100-900 range, which would ship nine files to no purpose.
const beVietnamPro = Be_Vietnam_Pro({
  variable: '--font-sans-family',
  subsets: ['latin', 'vietnamese'],
  weight: ['400', '500', '600'],
  display: 'swap',
});

// Monospace is retained deliberately and is NOT replaced: prices, order
// ids, tenant slugs and the KPI figures are set in it so digits align in
// columns and an id stays selectable as one unmistakable token. Those are
// semantic uses of a monospace face, not a stylistic leftover.
const geistMono = Geist_Mono({
  variable: '--font-mono-family',
  subsets: ['latin'],
  display: 'swap',
});

export async function generateMetadata(): Promise<Metadata> {
  const [tenant, origin] = await Promise.all([getCurrentTenant(), getRequestOrigin()]);
  if (!tenant) {
    return {
      title: 'Create Next App',
      description: 'Generated by create next app',
    };
  }

  const storeName = tenant.branding?.storeName || tenant.name;
  const tagline = tenant.branding?.tagline ?? null;
  const description = buildStoreDescription({
    storeName,
    tagline,
    ogDescription: tenant.branding?.ogDescription ?? null,
  });
  // The social-share title is deliberately distinct from the browser-tab
  // `title` below — see buildStoreOgTitle's own doc comment.
  const ogTitle = buildStoreOgTitle({ storeName, tagline });
  const logoUrl = tenant.branding?.logoUrl || undefined;

  return {
    // generateMetadata already reads a per-request origin (same pattern as
    // the product page and sitemap.ts), so metadataBase can be set here
    // without baking one tenant's host into a build-time constant — every
    // tenant's pages resolve their own OG image / canonical URLs against
    // their own request's origin.
    ...(origin ? { metadataBase: new URL(origin) } : {}),
    title: storeName,
    description,
    ...(origin ? { alternates: { canonical: origin } } : {}),
    icons: tenant.branding?.faviconUrl ? { icon: tenant.branding.faviconUrl } : undefined,
    openGraph: {
      title: ogTitle,
      description,
      ...(origin ? { url: origin } : {}),
      siteName: storeName,
      locale: 'vi_VN',
      type: 'website',
      ...(logoUrl ? { images: [{ url: logoUrl, alt: storeName }] } : {}),
    },
    twitter: {
      card: logoUrl ? 'summary_large_image' : 'summary',
      title: ogTitle,
      description,
      ...(logoUrl ? { images: [logoUrl] } : {}),
    },
  };
}

export async function generateViewport(): Promise<Viewport> {
  const tenant = await getCurrentTenant();
  const branding = tenant ? resolveBranding(tenant, tenant.branding) : null;
  return {
    width: 'device-width',
    initialScale: 1,
    ...(branding ? { themeColor: branding.primaryColor } : {}),
  };
}

export default async function RootLayout({ children }: LayoutProps<'/'>) {
  const locale = await getLocale();
  const dictionary = await getDictionary(locale);

  return (
    <ClerkProvider signInUrl="/sign-in">
      <html
        lang={locale}
        className={`${beVietnamPro.variable} ${geistMono.variable} h-full antialiased`}
        // The inline theme script below sets data-theme on this element
        // directly, before hydration — by design, so a returning visitor
        // never sees a one-frame flash of the wrong theme. That means
        // this element's attributes legitimately differ between what the
        // server rendered and what's in the DOM by the time React
        // hydrates; suppressHydrationWarning (React's own documented
        // escape hatch for exactly this pattern) tells React that's
        // expected here, without silencing mismatches anywhere else.
        suppressHydrationWarning
      >
        <head>
          {/* Sets data-theme on <html> BEFORE hydration/paint, so a
              returning visitor's saved light/dark/system choice never
              flashes the wrong theme for one frame. Reads the same
              localStorage key ThemeToggle.tsx writes; "system" (or
              nothing saved yet) resolves via matchMedia and leaves
              data-theme unset, so the existing
              @media(prefers-color-scheme) CSS blocks (shared by
              .admin-chrome and .storefront-glass) keep doing the work —
              this script's only job is the explicit light/dark override. */}
          <script
            dangerouslySetInnerHTML={{
              __html: `(function(){try{var m=localStorage.getItem('buyer-theme-mode');if(m==='light'||m==='dark'){document.documentElement.setAttribute('data-theme',m);}}catch(e){}})();`,
            }}
          />
        </head>
        <body className="min-h-full flex flex-col">
          <LocaleProvider locale={locale}>
            <DictionaryProvider dictionary={dictionary}>
              {children}
            </DictionaryProvider>
          </LocaleProvider>
        </body>
      </html>
    </ClerkProvider>
  );
}
